// @Summary Create a new outfit
// @Description Create a new outfit with specified items
// @Tags outfits
// @Accept json
// @Produce json
// @Param outfit body Outfit true "Outfit information"
// @Success 201 {object} Outfit
// @Failure 400 {object} ErrorResponse
// @Failure 500 {object} ErrorResponse
// @Router /outfits [post]
func createOutfit(c *gin.Context) {
	var newOutfit Outfit
	if err := c.ShouldBindJSON(&newOutfit); err != nil {
		c.JSON(http.StatusBadRequest, ErrorResponse{
			Error:   "Invalid request data",
			Code:    "VALIDATION_ERROR",
			Details: err.Error(),
		})
		return
	}

	// Validate required fields
	if newOutfit.ID == "" || newOutfit.Name == "" || len(newOutfit.ItemIDs) == 0 {
		c.JSON(http.StatusBadRequest, ErrorResponse{
			Error:   "Missing required fields",
			Code:    "MISSING_FIELDS",
			Details: "All fields (id, name, itemIds) are required and itemIds cannot be empty",
		})
		return
	}

	// Check if outfit with same ID already exists
	for _, outfit := range outfits {
		if outfit.ID == newOutfit.ID {
			c.JSON(http.StatusConflict, ErrorResponse{
				Error:   "Outfit already exists",
				Code:    "DUPLICATE_ID",
				Details: fmt.Sprintf("Outfit with ID %s already exists", newOutfit.ID),
			})
			return
		}
	}

	// Validate that all referenced items exist
	for _, itemID := range newOutfit.ItemIDs {
		itemExists := false
		for _, item := range items {
			if item.ID == itemID {
				itemExists = true
				break
			}
		}
		if !itemExists {
			c.JSON(http.StatusBadRequest, ErrorResponse{
				Error:   "Invalid item reference",
				Code:    "INVALID_ITEM_ID",
				Details: fmt.Sprintf("Item with ID %s does not exist", itemID),
			})
			return
		}
	}

	outfits = append(outfits, newOutfit)
	c.JSON(http.StatusCreated, SuccessResponse{
		Message: "Outfit created successfully",
		Data:    newOutfit,
	})
}

