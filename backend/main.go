// Item represents a clothing item.
// @Description A clothing item with basic information
type Item struct {
	ID       string `json:"id" example:"1" binding:"required"`
	Name     string `json:"name" example:"White T-Shirt" binding:"required"`
	Category string `json:"category" example:"Top" binding:"required"`
	ImageURL string `json:"imageUrl" example:"https://via.placeholder.com/150" binding:"required,url"`
}

// Outfit represents a combination of clothing items.
// @Description A combination of clothing items forming an outfit
type Outfit struct {
	ID      string   `json:"id" example:"1" binding:"required"`
	Name    string   `json:"name" example:"Casual Look" binding:"required"`
	ItemIDs []string `json:"itemIds" example:"1,2,3" binding:"required"`
}

// ErrorResponse represents a standardized error response
// @Description Standard error response format
type ErrorResponse struct {
	Error   string `json:"error" example:"Item not found"`
	Code    string `json:"code,omitempty" example:"NOT_FOUND"`
	Details string `json:"details,omitempty" example:"The requested item could not be found"`
}

// SuccessResponse represents a standardized success response
// @Description Standard success response format
type SuccessResponse struct {
	Message string      `json:"message" example:"Operation completed successfully"`
	Data    interface{} `json:"data"`
}

// In-memory storage (in production, this would be replaced with a database)
const mockImageUrl string = "https://via.placeholder.com/150"

var items = []Item{
	{ID: "1", Name: "White T-Shirt", Category: "Top", ImageURL: mockImageUrl},
	{ID: "2", Name: "Blue Jeans", Category: "Bottom", ImageURL: mockImageUrl},
	{ID: "3", Name: "Black Sneakers", Category: "Shoes", ImageURL: mockImageUrl},
}

var outfits = []Outfit{
	{ID: "1", Name: "Casual Look", ItemIDs: []string{"1", "2", "3"}},
}

// @Summary Get all items
// @Description Retrieve all clothing items
// @Tags items
// @Accept json
// @Produce json
// @Success 200 {array} Item
// @Failure 500 {object} ErrorResponse
// @Router /items [get]
func getItems(c *gin.Context) {
	c.JSON(http.StatusOK, SuccessResponse{
		Message: "Items retrieved successfully",
		Data:    items,
	})
}

// @Summary Get item by ID
// @Description Retrieve a specific clothing item by its ID
// @Tags items
// @Accept json
// @Produce json
// @Param id path string true "Item ID"
// @Success 200 {object} Item
// @Failure 404 {object} ErrorResponse
// @Failure 500 {object} ErrorResponse
// @Router /items/{id} [get]
func getItemByID(c *gin.Context) {
	id := c.Param("id")
	if id == "" {
		c.JSON(http.StatusBadRequest, ErrorResponse{
			Error:   "Item ID is required",
			Code:    "MISSING_ID",
			Details: "Please provide a valid item ID",
		})
		return
	}

	for _, item := range items {
		if item.ID == id {
			c.JSON(http.StatusOK, SuccessResponse{
				Message: "Item retrieved successfully",
				Data:    item,
			})
			return
		}
	}

	c.JSON(http.StatusNotFound, ErrorResponse{
		Error:   "Item not found",
		Code:    "NOT_FOUND",
		Details: fmt.Sprintf("Item with ID %s could not be found", id),
	})
}

// @Summary Create a new item
// @Description Create a new clothing item
// @Tags items
// @Accept json
// @Produce json
// @Param item body Item true "Item information"
// @Success 201 {object} Item
// @Failure 400 {object} ErrorResponse
// @Failure 500 {object} ErrorResponse
// @Router /items [post]
func createItem(c *gin.Context) {
	var newItem Item
	if err := c.ShouldBindJSON(&newItem); err != nil {
		c.JSON(http.StatusBadRequest, ErrorResponse{
			Error:   "Invalid request data",
			Code:    "VALIDATION_ERROR",
			Details: err.Error(),
		})
		return
	}

	// Validate required fields
	if newItem.ID == "" || newItem.Name == "" || newItem.Category == "" || newItem.ImageURL == "" {
		c.JSON(http.StatusBadRequest, ErrorResponse{
			Error:   "Missing required fields",
			Code:    "MISSING_FIELDS",
			Details: "All fields (id, name, category, imageUrl) are required",
		})
		return
	}

	// Check if item with same ID already exists
	for _, item := range items {
		if item.ID == newItem.ID {
			c.JSON(http.StatusConflict, ErrorResponse{
				Error:   "Item already exists",
				Code:    "DUPLICATE_ID",
				Details: fmt.Sprintf("Item with ID %s already exists", newItem.ID),
			})
			return
		}
	}

	items = append(items, newItem)
	c.JSON(http.StatusCreated, SuccessResponse{
		Message: "Item created successfully",
		Data:    newItem,
	})
}

