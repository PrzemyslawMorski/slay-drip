func main() {
	// Set Gin to release mode in production
	gin.SetMode(gin.ReleaseMode)

	r := gin.Default()

	// Add middleware for CORS, logging, etc.
	r.Use(gin.Logger())
	r.Use(gin.Recovery())

	// Health check endpoint
	r.GET("/health", healthCheck)

	// Swagger documentation endpoint
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// API v1 routes
	v1 := r.Group("/api/v1")
	{
		// Item routes
		v1.GET("/items", getItems)
		v1.GET("/items/:id", getItemByID)
		v1.POST("/items", createItem)

		// Outfit routes
		v1.GET("/outfits", getOutfits)
		v1.GET("/outfits/:id", getOutfitByID)
		v1.POST("/outfits", createOutfit)
	}

	// Start server with graceful shutdown
	srv := &http.Server{
		Addr:    ":8080",
		Handler: r,
	}

	fmt.Println("Server starting on :8080")
	fmt.Println("Swagger documentation available at: http://localhost:8080/swagger/index.html")

	if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
		fmt.Printf("Server error: %v\n", err)
	}
}
