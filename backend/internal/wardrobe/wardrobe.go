// Package wardrobe holds wardrobe photos for logged-in users. Anonymous uploads never
// reach this package (ADR-0004, amended for F02). Every method takes the owner from the
// verified token, so no caller can read or change another user's items.
package wardrobe

import (
	"context"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"time"

	"github.com/google/uuid"
)

// ErrNotFound means the item does not exist for this owner. Foreign items look the same
// (BE-42), so IDs cannot be probed.
var ErrNotFound = errors.New("not found")

// ErrConsentRequired means the owner has not granted consent to store wardrobe photos (BE-48).
var ErrConsentRequired = errors.New("consent required")

// DataTypeWardrobePhotos is the only consent type this package stores.
const DataTypeWardrobePhotos = "wardrobe_photos"

// Consent is the owner's current consent for one data type.
type Consent struct {
	Granted   bool
	GrantedAt *time.Time
}

// Item is one stored wardrobe photo. The photo bytes live in the blob store under Key.
type Item struct {
	ID          uuid.UUID
	Owner       string
	Key         string
	ContentType string
	SizeBytes   int
	CreatedAt   time.Time
}

// Repository stores consent and item metadata. Each method is scoped to one owner.
type Repository interface {
	// Consent returns the owner's consent, or a zero Consent when none was recorded.
	Consent(ctx context.Context, owner string) (Consent, error)
	// SetConsent records the owner's choice. Revoking also deletes every item the owner
	// has, in the same transaction, and returns those items so their photos can be removed.
	SetConsent(ctx context.Context, owner string, granted bool, at time.Time) ([]Item, error)
	InsertItem(ctx context.Context, item Item) error
	ListItems(ctx context.Context, owner string) ([]Item, error)
	// Item returns ErrNotFound for an unknown ID or an item owned by someone else.
	Item(ctx context.Context, owner string, id uuid.UUID) (Item, error)
	// DeleteItem returns ErrNotFound for an unknown ID or an item owned by someone else.
	DeleteItem(ctx context.Context, owner string, id uuid.UUID) (Item, error)
}

// Blobs stores the photo bytes. The key is generated by the server, never by a client.
type Blobs interface {
	Put(ctx context.Context, key string, data []byte, contentType string) error
	Get(ctx context.Context, key string) ([]byte, error)
	Delete(ctx context.Context, key string) error
}

// Service applies consent and photo rules on top of the ports.
type Service struct {
	repo  Repository
	blobs Blobs
	now   func() time.Time
	newID func() uuid.UUID
	log   *slog.Logger
}

// NewService returns a Service. Log lines never include owner IDs, keys or photo data.
func NewService(repo Repository, blobs Blobs, log *slog.Logger) *Service {
	return &Service{repo: repo, blobs: blobs, now: time.Now, newID: uuid.New, log: log}
}

// Consent returns the owner's wardrobe-photo consent.
func (s *Service) Consent(ctx context.Context, owner string) (Consent, error) {
	return s.repo.Consent(ctx, owner)
}

// SetConsent grants or revokes consent. Revoking deletes the owner's photos.
func (s *Service) SetConsent(ctx context.Context, owner string, granted bool) (Consent, error) {
	removed, err := s.repo.SetConsent(ctx, owner, granted, s.now())
	if err != nil {
		return Consent{}, fmt.Errorf("set consent: %w", err)
	}
	s.deleteBlobs(ctx, removed)
	return s.repo.Consent(ctx, owner)
}

// Add checks consent, sanitises the photo and stores it. The photo must be a JPEG, PNG
// or WebP image, judged by its bytes, not its file name.
func (s *Service) Add(ctx context.Context, owner string, raw []byte) (Item, error) {
	consent, err := s.repo.Consent(ctx, owner)
	if err != nil {
		return Item{}, fmt.Errorf("read consent: %w", err)
	}
	if !consent.Granted {
		return Item{}, ErrConsentRequired
	}
	photo, err := SanitisePhoto(raw)
	if err != nil {
		return Item{}, err
	}

	id := s.newID()
	item := Item{
		ID:          id,
		Owner:       owner,
		Key:         "wardrobe/" + id.String(),
		ContentType: photo.ContentType,
		SizeBytes:   len(photo.Data),
		CreatedAt:   s.now().UTC(),
	}
	if err := s.blobs.Put(ctx, item.Key, photo.Data, item.ContentType); err != nil {
		return Item{}, fmt.Errorf("store photo: %w", err)
	}
	if err := s.repo.InsertItem(ctx, item); err != nil {
		s.deleteBlobs(ctx, []Item{item})
		return Item{}, fmt.Errorf("record item: %w", err)
	}
	return item, nil
}

// List returns the owner's items, newest first.
func (s *Service) List(ctx context.Context, owner string) ([]Item, error) {
	return s.repo.ListItems(ctx, owner)
}

// Photo returns the item and its photo bytes for the owner.
func (s *Service) Photo(ctx context.Context, owner string, id uuid.UUID) (Item, []byte, error) {
	item, err := s.repo.Item(ctx, owner, id)
	if err != nil {
		return Item{}, nil, err
	}
	data, err := s.blobs.Get(ctx, item.Key)
	if err != nil {
		return Item{}, nil, fmt.Errorf("read photo: %w", err)
	}
	return item, data, nil
}

// Delete removes the owner's item and its photo.
func (s *Service) Delete(ctx context.Context, owner string, id uuid.UUID) error {
	item, err := s.repo.DeleteItem(ctx, owner, id)
	if err != nil {
		return err
	}
	s.deleteBlobs(ctx, []Item{item})
	return nil
}

// deleteBlobs removes photos after their rows are gone. A failure leaves an orphaned
// photo, which is logged by count only, so no key or owner appears in the logs.
func (s *Service) deleteBlobs(ctx context.Context, items []Item) {
	failed := 0
	for _, item := range items {
		if err := s.blobs.Delete(ctx, item.Key); err != nil {
			failed++
		}
	}
	if failed > 0 {
		s.log.WarnContext(ctx, "photo cleanup incomplete", "failed", failed, "total", len(items))
	}
}

// ReadAll reads at most limit bytes from r and reports whether more data followed.
func ReadAll(r io.Reader, limit int64) ([]byte, bool, error) {
	data, err := io.ReadAll(io.LimitReader(r, limit+1))
	if err != nil {
		return nil, false, err
	}
	if int64(len(data)) > limit {
		return nil, true, nil
	}
	return data, false, nil
}
